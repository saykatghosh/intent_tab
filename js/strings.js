// Locale used for numbers and dates in each language.
const LOCALES = { en: 'en', bn: 'bn-BD' };

let LANG = 'en';

export function getLang() {
  return LANG;
}

export function setLang(lang) {
  LANG = STRINGS[lang] ? lang : 'en';
}

export function locale() {
  return LOCALES[LANG] || LANG;
}

// Format a number with the current language's digits (e.g. ১২ in Bangla).
export function num(n) {
  return new Intl.NumberFormat(locale(), { useGrouping: false }).format(n);
}

// Convert any ASCII digits inside a string (used for "mm:ss").
export function digits(str) {
  return String(str).replace(/\d/g, (d) => num(Number(d)));
}

export function t(key, vars = {}) {
  const table = STRINGS[LANG] || STRINGS.en;
  let s = table[key] ?? STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll(`{${k}}`, typeof v === 'number' ? num(v) : v);
  }
  return s;
}

// Fill every element that has data-i18n / data-i18n-placeholder / data-i18n-title / data-i18n-aria.
export function applyStrings(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => (el.title = t(el.dataset.i18nTitle)));
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
  document.documentElement.lang = LANG;
  document.title = t('pageTitle');
}
